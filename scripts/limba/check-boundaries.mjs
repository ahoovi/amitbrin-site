import assert from 'node:assert/strict';
import { storageReady } from '../../src/lib/limba/store.ts';
import { readSession, accounts } from '../../src/lib/limba/session.ts';
process.env.NODE_ENV = 'development';
process.env.LIMBA_LOCAL_PREVIEW = '1';
delete process.env.VERCEL;
assert.equal(storageReady(), true);
process.env.NODE_ENV = 'production';
assert.equal(storageReady(), false, 'Production cannot use local event files');
process.env.NODE_ENV = 'development';
process.env.VERCEL = '1';
assert.equal(storageReady(), false, 'Vercel cannot use ephemeral local storage');
delete process.env.VERCEL;
delete process.env.LIMBA_LOCAL_PREVIEW;
assert.equal(storageReady(), false, 'Pilot requires explicit activation');
delete process.env.LIMBA_USERS_JSON;
assert.deepEqual(accounts(), []);
assert.equal(await readSession('unconfigured.session'), null);
console.log('PASS: 6 fail-closed configuration boundaries.');

import assert from 'node:assert/strict';
import { diagnosticItems,gradeItem,DIAGNOSTIC_VERSION,publicDiagnosticItems } from '../../src/lib/limba/diagnostic.ts';
import { diagnosticProgress,recommendTopic,highestAssistance } from '../../public/limba-personal/learning-model.js';
const items=publicDiagnosticItems();
const topics=[...new Set(items.map(i=>i.topic))].map(id=>({id}));
assert.equal(gradeItem('gender-2','cărți','none').rating,'independent');
assert.equal(gradeItem('gender-2','carti','none').near,true);
assert.equal(gradeItem('gender-2','cărți','theory').rating,'help');
assert.equal(gradeItem('afi-1',' SUNT! ','none').correct,true);
assert.equal(gradeItem('afi-1','suntem','none').correct,false);
assert.equal(highestAssistance('theory','hint'),'theory');
assert.equal(highestAssistance('none','hint'),'hint');
let events=[{kind:'self-report',topic:'routine20',rating:'independent',at:new Date().toISOString()}];
let p=diagnosticProgress(events,items,DIAGNOSTIC_VERSION);
assert.equal(p.completed,0);
assert.equal(recommendTopic(events,topics,p).item.id,'intro-1');
const make=(id,correct)=>({kind:'diagnostic',topic:items.find(i=>i.id===id).topic,rating:correct?'independent':'again',assistance:'none',at:new Date().toISOString(),diagnostic:{version:DIAGNOSTIC_VERSION,item:id,correct}});
events.push(make('intro-1',false),make('intro-1',true));
p=diagnosticProgress(events,items,DIAGNOSTIC_VERSION);
assert.equal(p.completed,1);assert.equal(p.independent,0);assert.equal(p.next.id,'intro-2');
assert.equal(recommendTopic(events,topics,p).kind,'diagnostic');
events=items.map((item,i)=>make(item.id,i!==2));
p=diagnosticProgress(events,items,DIAGNOSTIC_VERSION);
assert.equal(p.completed,12);assert.equal(p.independent,11);assert.equal(p.next,undefined);
assert.equal(recommendTopic(events,topics,p).topic.id,'afi2');
assert.equal(items.some(i=>'answers' in i),false);
assert.ok(diagnosticItems.every((i,n)=>n===0||i.lesson>=diagnosticItems[n-1].lesson));
console.log('PASS: 19 learning checks: early-first, resume, first evidence, assistance, diacritics, post-mapping recommendation.');
